"""FastAPI service for the health-facility staff-absenteeism model.

Routes
------
POST /predict  : validated inputs -> predicted absence rate
POST /retrain  : upload a CSV of new data -> the model is retrained and used immediately
GET  /docs     : Swagger UI (generated by FastAPI)

Run locally :  uvicorn prediction:app --reload
On Render   :  uvicorn prediction:app --host 0.0.0.0 --port $PORT
"""
import io
import os
from typing import Literal

import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field

import retrain as core

app = FastAPI(
    title="Health Facility Staff Absenteeism API",
    description=(
        "Predicts the share of health workers likely to be absent at a facility "
        "(0 = nobody absent, 1 = everybody absent) from basic facility characteristics. "
        "Built on World Bank Service Delivery Indicators (SDI) survey data. "
        "It is a risk indicator, not a real-time availability check."
    ),
    version="1.0.0",
)

# --------------------------------------------------------------------------------------
# CORS
# ALLOWED:    only the browser origins listed below (this API's own Render URL, for the Swagger UI,
#             and local development addresses, including the Flutter web debug server), only the
#             methods the API really uses (GET, POST), and only the headers a JSON/file-upload
#             request needs (Content-Type, Accept). Credentials are allowed so cookies/auth headers
#             could be added later without changing the policy.
# RESTRICTED: every other website. No wildcard "*": that would let any web page call this API from a
#             visitor's browser, and browsers refuse "*" combined with credentials anyway.
# NOTE:       the Flutter MOBILE app is not a browser, so CORS does not apply to it at all; this
#             configuration only controls which websites may call the API.
# --------------------------------------------------------------------------------------
ALLOWED_ORIGINS = [
    "https://health-facility-absence-api.onrender.com",   # TODO: replace with your real Render URL
    "http://localhost:8000",                    # local uvicorn (Swagger UI)
    "http://127.0.0.1:8000",
    "http://localhost:5000",                    # Flutter web debug (fixed port: --web-port 5000)
    "http://localhost:8080",
]
render_url = os.getenv("RENDER_EXTERNAL_URL")   # Render sets this automatically
if render_url and render_url not in ALLOWED_ORIGINS:
    ALLOWED_ORIGINS.append(render_url)

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=True,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
)

# Load the saved model from the repository when the service starts.
core.load_model()


class FacilityInput(BaseModel):
    """The 10 inputs of the model. Wrong type, missing value or out-of-range value => 422 validation error."""

    model_config = ConfigDict(
        extra="forbid",
        json_schema_extra={
            "example": {
                "country": "Tanzania-2014", "facility_level": "Health Post",
                "publicprivate": "Private", "ruralurban": "Rural",
                "has_autosyringe": 1, "has_dispsyringe": 1, "has_fridge": 1,
                "has_gloves": 1, "has_sharps": 1, "has_vaccarrier": 1,
            }
        },
    )

    # categorical (str) inputs: only the values seen in training are accepted
    country: Literal[
        "Kenya-2012", "Madagascar-2016", "Mozambique-2014", "Niger-2015", "Nigeria-2013",
        "Tanzania-2014", "Tanzania-2016", "Togo-2013", "Uganda-2013",
    ] = Field(..., description="Country-survey the facility belongs to")
    facility_level: Literal["Health Post", "Health Center", "Hospital"] = Field(..., description="Facility type")
    publicprivate: Literal["Public", "Private"] = Field(..., description="Ownership")
    ruralurban: Literal["Rural", "Urban"] = Field(..., description="Location type")

    # numeric (int) inputs: 0 = not available / not functioning, 1 = available / working
    has_autosyringe: int = Field(..., ge=0, le=1, strict=True, description="Auto-disable syringes available (0 or 1)")
    has_dispsyringe: int = Field(..., ge=0, le=1, strict=True, description="Disposable syringes available (0 or 1)")
    has_fridge: int = Field(..., ge=0, le=1, strict=True, description="Working refrigerator available (0 or 1)")
    has_gloves: int = Field(..., ge=0, le=1, strict=True, description="Gloves available (0 or 1)")
    has_sharps: int = Field(..., ge=0, le=1, strict=True, description="Sharps container available (0 or 1)")
    has_vaccarrier: int = Field(..., ge=0, le=1, strict=True, description="Vaccine carrier available (0 or 1)")


class PredictionOut(BaseModel):
    predicted_absence_rate: float = Field(..., description="Predicted share of staff absent (0 to 1)")
    predicted_absence_percent: float
    risk_level: str = Field(..., description="Illustrative label: Low < 25%, Moderate 25-50%, High > 50%")
    model: str


def risk_label(rate: float) -> str:
    return "Low" if rate < 0.25 else ("Moderate" if rate <= 0.50 else "High")


@app.get("/", include_in_schema=False)
def root():
    return {"service": "Health Facility Staff Absenteeism API", "docs": "/docs", "model": core.model_name()}


@app.post("/predict", response_model=PredictionOut)
def predict(payload: FacilityInput):
    """Predict the absence rate for one facility."""
    rate = core.predict_one(payload.model_dump())
    return PredictionOut(
        predicted_absence_rate=round(rate, 4),
        predicted_absence_percent=round(rate * 100, 1),
        risk_level=risk_label(rate),
        model=core.model_name(),
    )


@app.post("/retrain")
async def retrain(file: UploadFile = File(..., description="CSV with the same 11 columns as the training data")):
    """Upload a CSV of new facility data. Uploading triggers retraining; /predict uses the new model right away."""
    content = await file.read()
    if len(content) > 10_000_000:
        raise HTTPException(status_code=413, detail="File too large (limit 10 MB).")
    try:
        raw = pd.read_csv(io.BytesIO(content))
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the upload as a CSV file.")
    try:
        return await run_in_threadpool(core.retrain_model, raw)   # keep the event loop free while fitting
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))
